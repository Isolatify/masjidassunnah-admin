/* ─────────────────────────────────────────────────────────────────────────
   screens — kiosk display devices (the /screen Flutter app) that pair with
   the dashboard through a 6-digit code shown on the device itself.

   Flow: the device registers itself as `pending` via POST
   /api/screens/register (id + device_secret generated on the device), an
   admin types that code into "Link New Device" on /dashboard/screens
   (/api/screens/link, staff session required) and names it, and the row
   flips to `paired`. The device polls /api/screens/status with id + secret
   to pick the pairing up — and as a heartbeat for last_seen, which is what
   the dashboard reads as Online / Offline.

   All writes go through the service role (admin API routes). The signed-in
   dashboard only reads the list; the anon key never touches this table.
   ───────────────────────────────────────────────────────────────────────── */

create table if not exists public.screens (
  id            uuid primary key,          -- generated by the device
  device_id     text not null,             -- stable per install (informational)
  device_secret uuid not null,             -- proves ownership to the API
  code          text not null check (code ~ '^[0-9]{6}$'),
  status        text not null default 'pending'
                check (status in ('pending', 'paired')),
  name          text,                      -- set when an admin names the screen
  color         text not null default '#0f4a36',   -- display colorway
  last_seen     timestamptz,               -- heartbeat from the device
  created_at    timestamptz not null default now(),
  paired_at     timestamptz
);

-- Not unique on purpose: a wiped install re-registers as a fresh row. Any
-- stale `pending` rows left behind are harmless and can be pruned later.
create index if not exists screens_status_idx on public.screens (status);

alter table public.screens enable row level security;

-- The dashboard (signed-in staff) can read the list — codes included, so the
-- pairing screen can be re-checked; every write stays on the service role.
create policy "screens are readable by the dashboard"
  on public.screens for select
  to authenticated
  using (true);

grant select on public.screens to authenticated;
